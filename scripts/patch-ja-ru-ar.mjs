function deepMerge(target, source) {
  const result = { ...target };
  for (const [k, v] of Object.entries(source)) {
    if (k.includes('.')) {
      // Dotted key like 'language.en' — split into nested path
      const parts = k.split('.');
      let obj = result;
      for (let i = 0; i < parts.length - 1; i++) {
        obj[parts[i]] = obj[parts[i]] || {};
        obj = obj[parts[i]];
      }
      obj[parts[parts.length - 1]] = v;
    } else if (typeof v === 'object' && v !== null && !Array.isArray(v) && typeof result[k] === 'object') {
      result[k] = deepMerge(result[k], v);
    } else {
      result[k] = v;
    }
  }
  return result;
}

for (const [lang, patch] of Object.entries(patches)) {
  const filePath = `${LOCALES}/${lang}/translation.json`;
  const existing = JSON.parse(readFileSync(filePath, 'utf8'));
  const merged = deepMerge(existing, patch);
  writeFileSync(filePath, JSON.stringify(merged, null, 2) + '\n', 'utf8');
  console.log(`✓ ${lang}/translation.json updated`);
}

console.log('\nDone.');
