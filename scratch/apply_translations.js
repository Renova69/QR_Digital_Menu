function updateFile(file, langIndex) {
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  
  function apply(obj, prefix) {
    for (const key in obj) {
      if (typeof obj[key] === 'object') {
        apply(obj[key], prefix + key + '.');
      } else {
        const fullKey = prefix + key;
        const val = map[fullKey] || map[fullKey.replace(/\|.*/, '')];
        if (typeof val === 'string' && val.includes('|')) {
            obj[key] = val.split('|')[langIndex];
        } else if (Array.isArray(val)) {
            obj[key] = val[langIndex];
        } else if (typeof map[fullKey] === 'string') {
           obj[key] = map[fullKey]; // fallback
        }
      }
    }
  }
  apply(data, '');
  fs.writeFileSync(file, JSON.stringify(data, null, 2));
}

